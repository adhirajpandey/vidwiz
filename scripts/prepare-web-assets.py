"""Run with uv run scripts/prepare-web-assets.py; outputs are checked in."""
from pathlib import Path
from PIL import Image
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "frontend/src/assets"

for source in sorted((ROOT / "assets/landing").glob("*.jpg")):
    with Image.open(source) as image:
        # Keep original pixels for readable screenshots on high-density displays.
        image.save(OUT / "landing" / f"{source.stem}.webp", quality=85, method=6)

source = ROOT / "assets/brand/BricolageGrotesque.ttf"
all_chars = set(TTFont(source).getBestCmap())
latin = {c for c in all_chars if c <= 0xFF or 0x2000 <= c <= 0x206F or c in (0xFEFF, 0xFFFD)}
rules = []
for name, chars in [("latin", latin), ("extended", all_chars - latin)]:
    font = TTFont(source)
    options = subset.Options()
    options.flavor = "woff2"
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=chars)
    subsetter.subset(font)
    instantiateVariableFont(font, {"wght": (400, 800)}, inplace=True)
    font.flavor = "woff2"
    font.save(OUT / "fonts" / f"bricolage-{name}.woff2")
    ranges = ",".join(f"U+{c:X}" for c in sorted(chars))
    rules.append(f'''@font-face {{
  font-family: "Bricolage Grotesque";
  font-style: normal;
  font-weight: 400 800;
  font-stretch: 75% 100%;
  font-display: swap;
  src: url("./bricolage-{name}.woff2") format("woff2");
  unicode-range: {ranges};
}}''')
(OUT / "fonts/fonts.css").write_text("/* Generated by scripts/prepare-web-assets.py. */\n" + "\n".join(rules) + "\n", newline="\n")
(OUT / "fonts/OFL.txt").write_text("\n".join(line.rstrip() for line in (ROOT / "assets/brand/OFL.txt").read_text().splitlines()) + "\n", newline="\n")
